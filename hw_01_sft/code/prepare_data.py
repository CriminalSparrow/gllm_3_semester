def curate(groups):
    """Ручные редакционные правила после просмотра опасных групп, до обучения."""
    edits = []
    replacements = {
        3: (
            "Возможны пропуски зажигания из-за свечей, катушек, форсунок или других неисправностей; нужен осмотр.",
            "Снизьте нагрузку и безопасно остановитесь, заглушите двигатель. Не стирайте ошибки: в сервисе нужно считать коды и проверить зажигание и подачу топлива.",
            "При мигающем Check Engine и троении продолжать поездку не следует: можно повредить катализатор. Организуйте доставку в сервис на эвакуаторе.",
        ),
        4: (
            "Реальное снижение давления масла из-за уровня, фильтра, насоса или износа двигателя; также возможна неисправность датчика или проводки.",
            "Безопасно остановитесь и заглушите двигатель. На стоянке проверьте уровень по инструкции автомобиля. Не запускайте мотор для проверки лампы: фактическое давление должен измерить специалист.",
            "Красная лампа давления масла при работающем двигателе, даже периодическая, требует прекращения поездки до проверки. Нормальный уровень не доказывает нормальное давление; нужен эвакуатор.",
        ),
        6: (
            "Возможны утечка тормозной жидкости, воздух в гидроприводе, неисправность главного цилиндра или другой части тормозной системы.",
            "Безопасно остановитесь. На стоянке проверьте уровень жидкости и видимые следы утечки, сообщите симптомы сервису. Не проверяйте тормоза поездкой и не считайте долив устранением причины.",
            "Изменение педали или подозрение на утечку требуют проверки до дальнейшей езды. Не продолжайте поездку; организуйте эвакуатор.",
        ),
    }
    for index, sections in replacements.items():
        for row in groups[index]:
            old = row["messages"][-1]["content"]
            question = old.split("Уточнить:", 1)[1].strip()
            new = "\n".join([f"Возможные причины: {sections[0]}", f"Что делать: {sections[1]}",
                              f"Срочность: {sections[2]}", f"Уточнить: {question}"])
            assert check_answer(new)["pass"]
            row["messages"][-1]["content"] = new
            row["source"] += "+editorial_safety_rules"
            edits.append({"id": row["id"], "before": old, "after": new,
                          "reason": "Убрано разрешение продолжать поездку при опасном симптоме; уточнены причины и действия."})
    save_log("data_preparation", "editorial_edits", edits)
    return groups

def generate_topic(item):
    i, topic = item
    result = read_log("data_preparation").get("generations", {}).get(f"{i:02d}")
    if result is None:
        prompt = (
            f"Создай 8 разных учебных пар вопрос-ответ для темы автосервиса: {topic}. "
            "Вопросы на русском от клиентов, без персональных данных; разные симптомы и условия. "
            "Ответы 60–110 слов, каждый раздел непустой, заголовки без Markdown. "
            "Не выдумывай диагностику, цены, интервалы. Для опасных симптомов остановка и эвакуатор. "
            "Верни только JSON-массив из 8 объектов с ключами question и answer. "
            "Каждый answer НАЧИНАЕТСЯ с 'Возможные причины:' (без приветствия) и содержит "
            "в указанном порядке точные заголовки 'Возможные причины:', 'Что делать:', 'Срочность:', 'Уточнить:'. "
            "Не объединяй и не переименовывай разделы. Все 8 вопросов должны касаться именно указанной темы.\n" + SYSTEM
        )
        result = complete([{"role": "user", "content": prompt}], max_tokens=5000)
        save_log("data_preparation", "generations", result, entry=f"{i:02d}")
    rows = parse_json(result["text"])
    assert len(rows) == 8, (topic, len(rows))
    for row in rows:
        assert check_answer(row["answer"])["pass"], (topic, check_answer(row["answer"]))
    print(f"{i+1}/16: {topic}", flush=True)
    return [{"id": f"sft_{i:02d}_{j}", "topic": topic, "source": "synthetic:" + result["model"],
             "messages": [{"role": "system", "content": SYSTEM},
                          {"role": "user", "content": r["question"]},
                          {"role": "assistant", "content": r["answer"]}]}
            for j, r in enumerate(rows)]

def main():
    test = [{"id": f"test_{i+1:02d}", "question": q, "reference": r} for i, (q, r) in enumerate(TEST)]
    write_jsonl(ROOT / "data/test.jsonl", test)
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        groups = list(pool.map(generate_topic, enumerate(TOPICS)))
    groups = curate(groups)
    rng = random.Random(SEED)
    train, val = [], []
    for group in groups:
        rng.shuffle(group)
        val.extend(group[:1]); train.extend(group[1:])
    rng.shuffle(train)
    all_questions = [r["messages"][1]["content"].strip().lower() for r in train + val]
    assert len(set(all_questions)) == len(all_questions)
    assert not set(all_questions) & {r["question"].strip().lower() for r in test}
    write_jsonl(ROOT / "data/train.jsonl", train)
    write_jsonl(ROOT / "data/validation.jsonl", val)
    manifest = {"train": len(train), "validation": len(val), "test": len(test), "seed": SEED,
                "source": "Synthetic GLM (requested glm-4.7, reported glm-5.3-flash); 24 safety examples edited; separate test",
                "teacher_model_requested": "glm-4.7", "teacher_model_reported": "glm-5.3-flash",
                "split": "One generated example per topic held out for validation; fixed independent test",
                "sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in (ROOT / "data").glob("*.jsonl")}}
    (ROOT / "data/manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2))
    print(manifest)

if __name__ == "__main__":
    main()
